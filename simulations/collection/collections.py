"""
Collections read in a context (docs/collection_simulation_concept_v001.md).

A collection's members come three ways: listed in ``includes``, generated by
its ``membership_rule``, and through the collections it lists (nested). Each
carries a numeric weight from ``member_weights`` (default 1.0). Generated
members are worked out when read and never stored. A context from the asking
simulation narrows them (year) and judges each one (``check``).

Plant collections (Biosphere entities with ``collection_role``
``plant_collection``) read through the same API: a species' rarity becomes the
share of suitable ground the Biosphere gives that rarity.
"""
from dataclasses import dataclass

from world.entity_references import entity_reference_ids
from world.year_utils import parse_year


DEFAULT_WEIGHT = 1.0
COLLECTION_DATASET = "collections"
PLANT_COLLECTION_ROLE = "plant_collection"


@dataclass(frozen=True)
class Member:
    entity_id: str
    weight: float
    # "listed", "rule", or the id of the nested collection it came through
    source: str


@dataclass(frozen=True)
class Context:
    """What the asking simulation reads a collection for."""
    year: int = None
    check: object = None  # entity -> verdict, e.g. a list of shortfalls


@dataclass(frozen=True)
class ViewMember:
    member: Member
    entity: dict
    verdict: object = None


def _materialized(entity):
    materialize = getattr(entity, "materialize", None)
    return materialize() if callable(materialize) else entity


def _entity(world_model, entity_id):
    entity = world_model.get_entity(entity_id) if entity_id else None
    entity = _materialized(entity)
    return entity if isinstance(entity, dict) else None


def is_collection(entity):
    return isinstance(entity, dict) and (
        entity.get("_dataset") == COLLECTION_DATASET or entity.get("collection_role") == PLANT_COLLECTION_ROLE
    )


def _member_weights(collection):
    weights = {}
    for row in collection.get("member_weights") or []:
        if not isinstance(row, dict):
            continue
        try:
            weights[str(row.get("member"))] = float(row.get("weight"))
        except (TypeError, ValueError):
            continue
    return weights


def _lowered(value):
    values = value if isinstance(value, (list, tuple, set)) else [value]
    return {str(item).strip().lower() for item in values if item not in (None, "")}


def rule_matches(entity, rule):
    """
    Whether an entity passes a membership rule's filter:

        datasets        the entity's dataset is one of these
        field_values    {field: [allowed values]}; a list field matches if any item is allowed
        tags_all        every one of these tags
        tags_any        at least one of these tags
        fields_present  each of these fields has a value
    """
    datasets = rule.get("datasets")
    if datasets and entity.get("_dataset") not in datasets:
        return False
    for field_name, allowed in (rule.get("field_values") or {}).items():
        if not _lowered(entity.get(field_name)) & _lowered(allowed):
            return False
    tags = _lowered(entity.get("tags"))
    if not _lowered(rule.get("tags_all")) <= tags:
        return False
    tags_any = _lowered(rule.get("tags_any"))
    if tags_any and not tags_any & tags:
        return False
    return all(entity.get(name) not in (None, "", [], {}) for name in rule.get("fields_present") or [])


def _plant_members(collection):
    from simulations.biosphere.flora import RARITY_GROUND_SHARE

    members = []
    for record in collection.get("plant_records") or []:
        species_id = record.get("species") if isinstance(record, dict) else None
        if species_id:
            weight = RARITY_GROUND_SHARE.get(record.get("rarity"), RARITY_GROUND_SHARE["common"])
            members.append(Member(species_id, weight, "listed"))
    return members


def members(collection, world_model, _seen=None):
    """Every member of a collection, once each: listed first, then nested, then generated."""
    collection = _materialized(collection)
    if collection.get("collection_role") == PLANT_COLLECTION_ROLE:
        return _plant_members(collection)

    seen = set(_seen or ()) | {collection.get("id")}
    weights = _member_weights(collection)
    found = {}
    for reference in entity_reference_ids(collection.get("includes")):
        listed = _entity(world_model, reference)
        if is_collection(listed):
            if reference in seen:
                continue  # a collection that lists itself, directly or through others
            for inner in members(listed, world_model, seen):
                found.setdefault(inner.entity_id, Member(inner.entity_id, weights.get(inner.entity_id, inner.weight), reference))
        else:
            found.setdefault(reference, Member(reference, weights.get(reference, DEFAULT_WEIGHT), "listed"))

    rule = collection.get("membership_rule")
    if isinstance(rule, dict) and rule.get("datasets"):
        rule_weight = float(rule.get("weight", DEFAULT_WEIGHT))
        for dataset in rule["datasets"]:
            for candidate in world_model.get_entities_by_dataset(dataset):
                candidate = _materialized(candidate)
                if not isinstance(candidate, dict) or not candidate.get("id") or not rule_matches(candidate, rule):
                    continue
                entity_id = candidate["id"]
                found.setdefault(entity_id, Member(entity_id, weights.get(entity_id, rule_weight), "rule"))
    return list(found.values())


def _in_service(entity, year):
    """A member without dates counts as available: a missing year is not knowledge of absence."""
    start = parse_year(entity.get("start_year"))
    end = parse_year(entity.get("end_year"))
    return (start is None or start <= year) and (end is None or year <= end)


def view(collection, world_model, context=None):
    """The members as the context sees them: those present in its year, each with its verdict."""
    context = context or Context()
    out = []
    for member in members(collection, world_model):
        entity = _entity(world_model, member.entity_id)
        if entity is None:
            continue
        if context.year is not None and not _in_service(entity, context.year):
            continue
        verdict = context.check(entity) if context.check is not None else None
        out.append(ViewMember(member, entity, verdict))
    return out
